// Advisor evaluation on the planted-fault test set (src/advisor/evalCases.js).
//
//   npm run evaluate -- --provider mock                      (offline baseline, about 1 minute)
//   npm run evaluate -- --model gpt-4o --prompt v1           (real AI, prompt v1; about 10–30 AI calls)
//   npm run evaluate -- --model gpt-4o --prompt v2
//   npm run evaluate -- --case E04-high-reject --prompt v2   (one case only)
//
// Writes results/advisor-eval/<provider>-<model>-<prompt>.json (all details), results/advisor-eval/oracle.json (the
// best a brute-force lever search achieves, computed once), and results/advisor-eval/summary.md, which compares every
// run file in that folder. Every AI call is also logged in results/advisor-eval/eval-log.jsonl (tokens, seconds).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVAL_CASES } from '../src/advisor/evalCases.js';
import { evaluateAdvisor, oracleFor } from '../src/advisor/evaluate.js';
import { loadRateCard } from '../src/economics/rateCard.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'config', 'advisor.json'), 'utf8'));
const args = process.argv.slice(2);
const opt = (n) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : undefined; };
const provider = opt('provider') ?? cfg.provider;
const model = provider === 'mock' ? 'mock-rules' : (opt('model') ?? cfg.model);
const promptVersion = opt('prompt') ?? cfg.promptVersion ?? 'v1';
const only = opt('case');
const cases = only ? EVAL_CASES.filter((c) => c.id === only) : EVAL_CASES;
if (!cases.length) throw new Error(`unknown case ${only}`);

const outDir = path.join(root, 'results', 'advisor-eval');
fs.mkdirSync(outDir, { recursive: true });
const rates = loadRateCard();

// Oracle (deterministic, cached)
const oracleFile = path.join(outDir, 'oracle.json');
let oracle = fs.existsSync(oracleFile) ? JSON.parse(fs.readFileSync(oracleFile, 'utf8')) : {};
if (args.includes('--oracle') || EVAL_CASES.some((c) => !oracle[c.id])) {
  oracle = {};
  for (const c of EVAL_CASES) { oracle[c.id] = await oracleFor(c, rates); process.stdout.write(`oracle ${c.id}: +${oracle[c.id].gain.toFixed(1)} points\n`); }
  fs.writeFileSync(oracleFile, JSON.stringify(oracle, null, 2) + '\n');
}

const t0 = Date.now();
const { results, summary } = await evaluateAdvisor({
  cases, rates, oracle, provider, model, promptVersion, temperature: cfg.temperature, maxTokens: cfg.maxTokens,
  maxRounds: cfg.maxRounds, timeoutMs: cfg.timeoutMs, logFile: path.join(outDir, 'eval-log.jsonl'),
});
const tag = `${provider}-${model}-${promptVersion}${only ? `-${only}` : ''}`.replace(/[^\w.-]+/g, '_');
fs.writeFileSync(path.join(outDir, `${tag}.json`), JSON.stringify({ provider, model, promptVersion, summary, results }, null, 2) + '\n');
console.log(`${tag}: ${cases.length} cases in ${((Date.now() - t0) / 1000).toFixed(0)} s`);

// Summary across all full runs in the folder
const pctf = (x) => `${Math.round(100 * x)}%`;
const runs = fs.readdirSync(outDir).filter((f) => f.endsWith('.json') && f !== 'oracle.json')
  .map((f) => JSON.parse(fs.readFileSync(path.join(outDir, f), 'utf8'))).filter((r) => r.results.length === EVAL_CASES.length)
  .sort((a, b) => `${a.provider}${a.model}${a.promptVersion}`.localeCompare(`${b.provider}${b.model}${b.promptVersion}`));
const md = [
  '# Advisor evaluation', '',
  `Planted-fault test set: ${EVAL_CASES.length} cases (src/advisor/evalCases.js), each with a known cause. Generated by \`npm run evaluate\`. `
  + 'Oracle = best verified service-level gain from a brute-force search over a fixed grid of lever changes (no AI).', '',
  '| Advisor | Prompt | Top cause right | Cause found | Wrong causes per case | Valid citations | Valid proposals | Fixes the root cause | Solved (verified) | Regret vs oracle (points) | Rounds per case | Tokens per case | Seconds per case |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
  ...runs.map((r) => { const s = r.summary; return `| ${r.provider === 'mock' ? 'mock (rules)' : r.model} | ${r.promptVersion} | ${pctf(s.topCauseHit)} | ${pctf(s.anyCauseHit)} | ${s.falseCausesPerCase.toFixed(1)} | ${pctf(s.citationValid)} | ${pctf(s.validProposals)} | ${pctf(s.rootFix)} | ${pctf(s.solved)} | ${s.meanRegret.toFixed(1)} | ${s.roundsPerCase.toFixed(1)} | ${Math.round(s.tokensPerCase)} | ${s.secondsPerCase.toFixed(1)} |`; }),
  '', '## Per case', '',
  ...EVAL_CASES.flatMap((c) => [
    `### ${c.id}: ${c.description}`, '',
    `Expected cause: ${c.primary.join(' or ')}; root-cause levers: ${c.rootLevers.join(', ') || 'none (nothing to fix)'}; oracle: +${(oracle[c.id]?.gain ?? 0).toFixed(1)} points with ${JSON.stringify(oracle[c.id]?.levers)}.`, '',
    '| Advisor | Prompt | Top cause (scored as) | Cause found | Root fix | Solved | Best Δ SL | Rounds |',
    '|---|---|---|---|---|---|---|---|',
    ...runs.map((r) => { const x = r.results.find((y) => y.case === c.id); const top = x.answer?.rootCauses?.[0];
      return `| ${r.provider === 'mock' ? 'mock (rules)' : r.model} | ${r.promptVersion} | ${top ? `${top.cause} (${top.scoredAs.join(', ') || '?'})` : '–'} | ${x.anyCauseHit ? 'yes' : 'no'} | ${x.rootFix ? 'yes' : 'no'} | ${x.solved ? 'yes' : 'no'} | ${x.slGain ? `+${x.slGain.toFixed(1)}` : '–'} | ${x.rounds} |`; }),
    '',
  ]),
].join('\n');
fs.writeFileSync(path.join(outDir, 'summary.md'), md);
console.log(`Summary: results/advisor-eval/summary.md (${runs.length} full run(s) compared)`);
console.log(JSON.stringify(summary));
