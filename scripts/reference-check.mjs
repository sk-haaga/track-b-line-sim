// Reference check: do the four reference scenarios still give the reference results? (assumption SIM-05)
//
//   npm run reference            (or: node scripts/reference-check.mjs)
//
// Official check: the average service level of seeds 1 and 2 must lie within the tolerance of the reference value
// (about ±2 points, ±5 points in the scenarios with the outage). For context it also runs seeds 1–30 and reports mean
// and standard deviation, to compare with the spread the data README reports for the unseeded starter.
// Writes results/reference-check.md and exits with code 1 if an official check fails.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runHeadless } from '../src/headless/run.js';
import { REFERENCE_SCENARIOS, REFERENCE_SEEDS, SHIFTS, demandFor, configFor } from '../src/scenarios/reference.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, '..', 'results');
const SPREAD_SEEDS = Array.from({ length: 30 }, (_, i) => i + 1);

const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const sd = (a) => { const m = mean(a); return Math.sqrt(a.reduce((s, x) => s + (x - m) ** 2, 0) / (a.length - 1)); };
const pct = (x, d = 1) => (100 * x).toFixed(d);

async function run(scenario, seed) {
  const r = await runHeadless({ config: configFor(scenario), seed, shifts: SHIFTS, demand: demandFor(scenario.demand) });
  return {
    serviceLevel: r.kpis.serviceLevel,
    goodPerShift: r.kpis.goodPerShift,
    scrapRate: r.kpis.scrap / Math.max(1, r.kpis.released),
    scrap: r.kpis.scrap,
    avgWip: r.kpis.avgWip,
  };
}

const rows = [];
let allPassed = true;
for (const sc of REFERENCE_SCENARIOS) {
  const official = [];
  for (const seed of REFERENCE_SEEDS) official.push(await run(sc, seed));
  const spread = [];
  for (const seed of SPREAD_SEEDS) spread.push(await run(sc, seed));
  const sl = mean(official.map((r) => r.serviceLevel));
  const pass = Math.abs(sl - sc.referenceServiceLevel) <= sc.tolerance + 1e-9;
  allPassed &&= pass;
  rows.push({
    scenario: sc.id,
    seed1: pct(official[0].serviceLevel), seed2: pct(official[1].serviceLevel), avg: pct(sl),
    reference: pct(sc.referenceServiceLevel, 0), tolerance: `±${pct(sc.tolerance, 0)}`, result: pass ? 'PASS' : 'FAIL',
    goodPerShift: mean(official.map((r) => r.goodPerShift)).toFixed(1),
    scrapRate: pct(mean(official.map((r) => r.scrapRate))),
    avgWip: mean(official.map((r) => r.avgWip)).toFixed(1),
    sl30: `${pct(mean(spread.map((r) => r.serviceLevel)))} ± ${pct(sd(spread.map((r) => r.serviceLevel)))}`,
    scrap30: `${mean(spread.map((r) => r.scrap)).toFixed(0)} ± ${sd(spread.map((r) => r.scrap)).toFixed(0)}`,
  });
}

const md = [
  '# Reference check',
  '',
  `Generated by \`npm run reference\`. ${SHIFTS} shifts per scenario, empty line and empty finished-goods stock at the start, outage set in the engine (\`config.source.outage\`).`,
  '',
  '| Scenario | SL seed 1 (%) | SL seed 2 (%) | SL avg (%) | Reference (%) | Tolerance | Result | Good/shift | Scrap rate (%) | Avg WIP | SL seeds 1–30, mean ± sd | Scrap seeds 1–30, mean ± sd |',
  '|---|---|---|---|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.scenario} | ${r.seed1} | ${r.seed2} | ${r.avg} | ${r.reference} | ${r.tolerance} | ${r.result} | ${r.goodPerShift} | ${r.scrapRate} | ${r.avgWip} | ${r.sl30} | ${r.scrap30} |`),
  '',
  'SL = service level: units shipped on time / units ordered. Good/shift, scrap rate and WIP are averages of seeds 1 and 2.',
  '',
].join('\n');

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'reference-check.md'), md);
console.log(md);
console.log(allPassed ? 'REFERENCE CHECK PASSED' : 'REFERENCE CHECK FAILED');
process.exit(allPassed ? 0 : 1);
